import tseslint from "typescript-eslint";
import svelte from "eslint-plugin-svelte";

/**
 * Build output, tooling caches, and inputs this project does not own.
 * `docs/**` and `tests/fixtures/**` are given deliverables (product brief,
 * design system, sanitized feed fixtures) and must not be reformatted or
 * linted by this project's toolchain.
 */
const ignoredPaths = [
  "node_modules/",
  "build/",
  ".svelte-kit/",
  ".vite/",
  "coverage/",
  "test-results/",
  "playwright-report/",
  "playwright/.cache/",
  "docs/**",
  "tests/fixtures/**"
  // Git-ignored private working directory: its contents are tool output, not
  // project source, and must never be linted or formatted.
];

// Declared explicitly rather than via the `globals` package, so the toolchain
// stays to the dependency set named in docs/ARCHITECTURE.md §2 plus the
// TypeScript parser it requires for `.ts` files. The JSDoc annotation is
// ESLint 10's `GlobalVariableOption` union, so the object satisfies
// `GlobalsConfig` without widening every entry to `string`.
/**
 * @type {Record<string, "off" | "readable" | "readonly" | "writable" | "writeable">}
 */
const browserAndNodeGlobals = {
  console: "readonly",
  document: "readonly",
  window: "readonly",
  navigator: "readonly",
  localStorage: "readonly",
  fetch: "readonly",
  URL: "readonly",
  URLSearchParams: "readonly",
  AbortController: "readonly",
  AbortSignal: "readonly",
  setTimeout: "readonly",
  clearTimeout: "readonly",
  setInterval: "readonly",
  clearInterval: "readonly",
  requestAnimationFrame: "readonly",
  HTMLElement: "readonly",
  HTMLAudioElement: "readonly",
  process: "readonly"
};

export default tseslint.config(
  { ignores: ignoredPaths },
  ...tseslint.configs.recommended,
  {
    languageOptions: {
      ecmaVersion: 2022,
      sourceType: "module",
      globals: browserAndNodeGlobals
    },
    rules: {
      // TypeScript reports undefined identifiers, shadowed names, and unused
      // imports with better precision than the ESLint core rules.
      "no-undef": "off",
      "no-unused-vars": "off",
      "@typescript-eslint/no-unused-vars": [
        "error",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_" }
      ]
    }
  },
  ...svelte.configs["flat/recommended"],
  {
    // `.svelte` files need the TypeScript parser handed to
    // `svelte-eslint-parser` explicitly: without it the script block is parsed
    // as plain JavaScript and TypeScript syntax (`interface`, `as`,
    // destructured `let { x }` props) is a parse error.
    files: ["**/*.svelte", "**/*.svelte.ts", "**/*.svelte.js"],
    languageOptions: {
      parserOptions: {
        parser: tseslint.parser
      }
    }
  },
  {
    // `resolve()` exists to prefix a pathname with `paths.base`, and this
    // project sets neither `paths.base` nor `paths.relative`, so it is the
    // identity function here. It is also typed against the route manifest
    // generated by `svelte-kit sync`, which contains only the routes that
    // exist today — so it cannot express the per-slug routes (`/episodes/…`,
    // `/people/…`, `/topics/…`) until those are added, and enabling it would
    // fail the type check on links that are already correct.
    //
    // If a base path or relative paths is ever configured, re-enable this rule
    // so every internal link is route-aware again.
    rules: {
      "svelte/no-navigation-without-resolve": "off"
    }
  }
);
